    private void btnGravarCadastroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGravarCadastroActionPerformed
        if (txtPartido.getText().trim().isEmpty()) {            
            JOptionPane.showMessageDialog(this, "Preencha o numero do partido!",
                    "Campo vazio", JOptionPane.WARNING_MESSAGE);
            txtPartido.requestFocus();
            return;
        }
        
        if (txtNomeCandidato.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha o nome do(a) candidato(a)!",
                    "Campo vazio", JOptionPane.WARNING_MESSAGE);
            txtNomeCandidato.requestFocus();
            return;
        }
      
        try {
            String nome = txtNomeCandidato.getText();
            int numPartido = Integer.parseInt(txtPartido.getText());

            Candidato candidato = new Candidato();
            candidato.setNome(nome);
            candidato.setNumeroDoPartido(numPartido);
            cliente.cadastrarCandidato(candidato);
            
            txtNomeCandidato.setText("");
            txtPartido.setText("");
            txtPartido.requestFocus();
            
            atualizaComboCandidatos();   
        } catch (RemoteException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Erro", 
                    JOptionPane.WARNING_MESSAGE);
        } catch (CandidatoExisteException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Atenção", 
                    JOptionPane.WARNING_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Erro ao cadastrar! "
                            + ex.getMessage(), "Erro", 
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGravarCadastroActionPerformed

    private void btnEnviarVotosAoServidorCentralActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnviarVotosAoServidorCentralActionPerformed
        int numeroPartido = 0;
        int qtdVotosCandidatoSelecionado = 0;
        
        if (txtQtdVotos.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Informe a quantidade de votos" 
                        , "Campo vazio", JOptionPane.WARNING_MESSAGE);
            txtQtdVotos.requestFocus();
            return;
        }
                
        Candidato candidatoSelecionado = (Candidato)cbbCanditatos.getSelectedItem();
        
        int resposta = JOptionPane.showConfirmDialog(
                null, 
                "Registrar votos para o(a) candidato(a) " +candidatoSelecionado.toString() +"?",
                "Registros de Votos",
                JOptionPane.YES_NO_OPTION                     
        );
        
        if (resposta == JOptionPane.NO_OPTION) {
            return;
        }
        
        if (candidatoSelecionado != null) {
            
            try {
                numeroPartido = candidatoSelecionado.getNumeroDoPartido();
                qtdVotosCandidatoSelecionado = Integer.parseInt(txtQtdVotos.getText());
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(this, "Digite número válido!", "Erro", 
                         JOptionPane.WARNING_MESSAGE);  
            }
            
            if (qtdVotosCandidatoSelecionado < 1) {
                JOptionPane.showMessageDialog(this, "Quatidade de votos deve ser maior que zero!", 
                        "Erro", JOptionPane.WARNING_MESSAGE);  
            }
            
            try {
                cliente.registrarVotos(numeroPartido, qtdVotosCandidatoSelecionado);
                
                txtRetorno.setText("Votos do(a) candidato(a) "+candidatoSelecionado.toString()
                        + " enviados com sucesso!");
                
                txtQtdVotos.setText(""); 
            } catch (RemoteException ex) {
                JOptionPane.showMessageDialog(this, "Erro ao Registrar Votos! " 
                         + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Erro ao Registrar Votos! " 
                         + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnEnviarVotosAoServidorCentralActionPerformed

