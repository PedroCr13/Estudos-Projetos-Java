    private void btnEncerrarUrnaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEncerrarUrnaActionPerformed
        
        int resposta = JOptionPane.showConfirmDialog(
                null, 
                "Confirma Encerramento da urna?",
                "Encerrar Urna",
                JOptionPane.YES_NO_OPTION                     
        );
        
        if (resposta == JOptionPane.YES_OPTION) {
            cliente.desconectar();
            txtPartido.setEnabled(false);
            txtNomeCandidato.setEnabled(false);
            cbbCanditatos.setEnabled(false);
            txtQtdVotos.setEnabled(false);
            btnGravarCadastro.setEnabled(false);
            btnEnviarVotosAoServidorCentral.setEnabled(false);
            btnEncerrarUrna.setEnabled(false);
            txtRetorno.setText("Sessão encerrada!");
        }
    }//GEN-LAST:event_btnEncerrarUrnaActionPerformed

