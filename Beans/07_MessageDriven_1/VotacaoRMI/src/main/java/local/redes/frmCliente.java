    public void atualizaComboCandidatos() {
        try {
            cbbCanditatos.removeAllItems();
            
            List<Candidato> lista = cliente.obterListaDeCandidatos();

            for (Candidato c : lista) {
                cbbCanditatos.addItem(c);
            }
           
        } catch (RemoteException ex) {
            JOptionPane.showMessageDialog(this, "Erro listar candidatos! " 
                    + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);   
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Erro ao listar candidatos! "
                    + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

