public class Operad {

	public static void main(String args[]){
		System.out.println("Impressão de Resultado de Cálculos:");
		System.out.println("");
		int a = 3, b = 2;
		int c = a + b;
		
		int divisao = a / b;
		int multiplicacao = a * b;
		int subtracao = a - b;
		System.out.println("O resultado da soma de A e B é: " + c);
		System.out.println("a  * b: " + multiplicacao);
		System.out.println("a / b: " + divisao);
		System.out.println("a - b " + subtracao);
	}
}